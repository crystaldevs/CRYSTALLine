# ── geometry block: 2D slabs and 1D polymers ───────────────────────────────
def _slab(pbc=(True, True, False)) -> Structure:
    """A two-atom MgO-like slab; ``pbc`` picks which direction is the vacuum."""
    cell = np.diag([4.21, 4.21, 4.21])
    aperiodic = pbc.index(False)
    cell[aperiodic, aperiodic] = 500.0  # CRYSTAL's formal vacuum thickness
    periodic = [i for i, p in enumerate(pbc) if p]
    second = np.zeros(3)
    second[periodic[0]] = second[periodic[1]] = 2.105
    return Structure.from_ase(
        Atoms("MgO", positions=[[0, 0, 0], second], cell=cell, pbc=pbc)
    )


def _polymer(pbc=(True, False, False)) -> Structure:
    """A CH2 repeat unit; ``pbc`` picks which direction is the chain axis."""
    cell = np.diag([500.0, 500.0, 500.0])
    axis = pbc.index(True)
    cell[axis, axis] = 2.5
    others = [i for i in range(3) if i != axis]
    h1, h2 = np.zeros(3), np.zeros(3)
    h1[axis] = h2[axis] = 0.6
    h1[others[0]] = 0.9
    h2[others[0]] = -0.9
    return Structure.from_ase(
        Atoms("CH2", positions=[[0, 0, 0], h1, h2], cell=cell, pbc=pbc)
    )


def test_slab_uses_layer_group_1_with_in_plane_parameters():
    lines = _lines(build_input(_slab()))
    assert lines[1] == "SLAB"
    assert lines[2] == "1"  # layer group p1
    assert lines[3] == "4.210000 4.210000 90.000000"  # a, b, gamma
    assert lines[4] == "2"


def test_slab_coordinates_are_fractional_in_plane_and_angstrom_out_of_plane():
    lines = _lines(build_input(_slab()))
    mg, o = lines[5].split(), lines[6].split()
    assert int(mg[0]) == 12 and int(o[0]) == 8
    # the second atom sits at half the cell along both periodic directions ...
    assert abs(float(o[1]) - 0.5) < 1e-9 and abs(float(o[2]) - 0.5) < 1e-9
    # ... and both atoms lie in the plane, so z is 0 Angstrom (not fractional)
    assert abs(float(mg[3])) < 1e-9 and abs(float(o[3])) < 1e-9


def test_slab_with_another_vacuum_axis_is_rotated_into_the_xy_plane():
    # CRYSTAL requires the slab in xy; an x- or y-aperiodic cell must be rotated,
    # and must give the same deck as the already-oriented one.
    reference = _lines(build_input(_slab((True, True, False))))[1:]
    for pbc in ((False, True, True), (True, False, True)):
        assert _lines(build_input(_slab(pbc)))[1:] == reference


def test_polymer_uses_rod_group_1_and_one_lattice_parameter():
    lines = _lines(build_input(_polymer()))
    assert lines[1] == "POLYMER"
    assert lines[2] == "1"  # rod group p1
    assert lines[3] == "2.500000"  # the repeat length only
    assert lines[4] == "3"


def test_polymer_coordinates_are_fractional_along_x_only():
    lines = _lines(build_input(_polymer()))
    carbon, hydrogen = lines[5].split(), lines[6].split()
    assert int(carbon[0]) == 6 and int(hydrogen[0]) == 1
    # x is fractional: 0.6 A along a 2.5 A repeat
    assert abs(float(hydrogen[1]) - 0.24) < 1e-9
    # y and z stay in Angstrom
    assert abs(abs(float(hydrogen[2])) - 0.9) < 1e-9


def test_polymer_along_another_axis_keeps_its_repeat_length():
    for pbc in ((False, True, False), (False, False, True)):
        lines = _lines(build_input(_polymer(pbc)))
        assert lines[3] == "2.500000"
        # the chain-axis fraction survives the rotation
        assert abs(float(lines[6].split()[1]) - 0.24) < 1e-9


