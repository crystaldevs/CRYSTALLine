def test_intcphf_block_carries_cphf_keywords():
    deck = build_input(
        _nacl(),
        CrystalInputSpec(
            task=TaskOptions(
                kind="FREQCALC",
                freq=FreqOptions(
                    raman_intensities=True,
                    cphf=CphfOptions(fmixing=60, maxcycle=200, fmixing2=60, maxcycle2=200),
                ),
            )
        ),
    )
    block = _freq_block(deck)
    assert block.index("INTRAMAN") < block.index("INTCPHF")  # manual's ordering
    i = block.index("INTCPHF")
