def test_exchange_only_and_correlation_only_are_both_valid():
    # No CORRELAT is an exchange-only functional; no EXCHANGE keeps HF exchange.
    x_only = build_input(
        _nacl(), CrystalInputSpec(method=MethodOptions(functional_mode="SPLIT", exchange="PBE"))
    )
    assert "CORRELAT" not in _lines(x_only)
    c_only = build_input(
        _nacl(), CrystalInputSpec(method=MethodOptions(functional_mode="SPLIT", correlation="PWGGA"))
    )
    assert "EXCHANGE" not in _lines(c_only)
    assert "CORRELAT" in _lines(c_only)


