def _lines(deck: str) -> list[str]:
    return deck.splitlines()


def _nacl() -> Structure:
    return Structure.from_ase(bulk("NaCl", "rocksalt", a=5.64))


def _rutile() -> Structure:
    atoms = ase_crystal(
        ["Ti", "O"],
        basis=[(0, 0, 0), (0.305, 0.305, 0.0)],
        spacegroup=136,
        cellpar=[4.59, 4.59, 2.96, 90, 90, 90],
    )
    return Structure.from_ase(atoms)


def _co_molecule() -> Structure:
    mol = Structure.empty()
    mol.add_atom("C", [0.0, 0.0, 0.0])
    mol.add_atom("O", [0.0, 0.0, 1.128])
    return mol


# ── geometry block: 3D crystals ────────────────────────────────────────────
def test_nacl_geometry_is_symmetry_reduced_cubic():
    deck = build_input(_nacl())
    lines = _lines(deck)
    assert lines[0] == "Generated by CRYSTALLine"  # title
    assert lines[1] == "CRYSTAL"
    assert lines[2] == "0 0 0"  # IFLAG IFHR IFSO
    assert lines[3] == "225"  # space group Fm-3m
    assert lines[4] == "5.640000"  # cubic: a single "a" parameter
    assert lines[5] == "2"  # two atoms in the asymmetric unit (Na, Cl)
    # the two irreducible atoms are Na (11) and Cl (17)
    zs = sorted(int(lines[6 + i].split()[0]) for i in range(2))
    assert zs == [11, 17]


def test_rutile_prints_a_and_c_for_tetragonal():
    deck = build_input(_rutile())
    lines = _lines(deck)
    assert lines[1] == "CRYSTAL"
    assert lines[3] == "136"  # P4_2/mnm
    # tetragonal -> minimal set is (a, c): two numbers on the lattice line
    latt = lines[4].split()
    assert len(latt) == 2
    assert abs(float(latt[0]) - 4.59) < 1e-2 and abs(float(latt[1]) - 2.96) < 1e-2
    assert lines[5] == "2"  # Ti and O irreducible


